	@Override
	public int getFeatureHeight() {
		return 16;
	}

	protected int rotateX(int x, int z, boolean rotated) {
		return rotated ? z : x;
	}

	protected int rotateZ(int x, int z, boolean rotated) {
		return rotated ? x : z;
	}
	
	@Override
	public void generateSchematic(World world, Random rand, BiomeGenBase biome, int chunkX, int chunkZ) {
		this.fillSchematic((short)-1);
		
		short [][][] piece = wrecks[rand.nextInt(wrecks.length)];
		boolean rotated = rand.nextBoolean();
		
		int pieceWidth = piece.length;
		int pieceLength = piece[2].length; // Whack, but faster
		
		int xO = rand.nextInt(17 - pieceWidth);
		int zO = rand.nextInt(17 - pieceLength);
		
		int x0 = this.rotateX(xO, zO, rotated);
		int z0 = this.rotateZ(xO, zO, rotated);
		
		for(int x = 0; x < piece.length; x ++) {
			for(int z = 0; z < piece[x].length; z ++) {
				for(int y = 0; y < piece[x][z].length; y ++) {
					short s = piece[x][z][y];
					if(s >= 0) {					
						int blockID = s & 0xff;
						int meta = s >> 8;
						if(rotated) {
							meta = this.rotateMeta(blockID, meta);
							s = (short)(blockID | (meta << 8));
						}
						
						this.schematic[x0 + this.rotateX(x, z, rotated)][z0 + this.rotateZ(x, z, rotated)][y] = s;
						
						// Special blocks: chests and spawners. 
						// Shiny glass (147) is here so it is put out in the populate stage and brightness y handled properly	
						if(blockID == 52 || blockID == 54 || blockID == 147 || blockID == 151) {
							this.addSpecialBlock(x0 + this.rotateX(x, z, rotated), y, z0 + this.rotateZ(x, z, rotated), blockID, meta);
						}
					}
				}
			}
		}
		
		System.out.println ("Wreck @ " + this.centerX + " " + this.centerZ);
	}
	
	protected int rotateMeta(int blockID, int meta) {

		// Rotate block? NORTH<->WEST, SOUTH<->EAST
		switch(blockID) {
		case 17: 
			// Log 12<->4
			
			if(meta == 4) {
				meta = 12;
			} else if(meta == 12) {
				meta = 4;
			}
			break;
		case 65: 
			// Stairs 2<->4, 3<->5
		case 54: 
			// Chests 2<->4, 3<->5
			meta ^= 6;	
			break; 	
		case 53: 
			// Stair Compact Planks 1<->3 0<->2
		case 96: 
			// Trap Door 1<->3 0<->2
			meta ^= 2; 
			break;
		}
		
		return meta;
	}

